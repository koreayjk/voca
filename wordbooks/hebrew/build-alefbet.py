# 끝글자(소피트) 안내 — 본 글자 카드 안에 같이 넣는다(따로 5장을 더 만들지 않는다)
def tip_of(num, sofit, letter, name):
    bits = ['숫자값 %d' % num]
    if sofit:
        bits.append('끝글자 %s — 단어 끝에 올 때는 이 모양으로 씁니다' % sofit)
    if letter == 'שׁ':
        bits.append('점이 왼쪽이면 שׂ(신) — 음가 s')
    return ' · '.join(bits)

def to_word(r):
    num, letter, sofit, name, sound, gematria, picto, mean, ex, ex_read, ex_ko = r
    # 앞면은 '글자만' 보여준다 → ipa 를 비운다(ipa 는 앞·뒤 양쪽에 찍힌다).
    # 이름·음가는 뒷면 ① 번으로 내린다. 글자를 보고 이름이 떠올라야 읽을 수 있다.
    meanings = [
        {'pos': '', 'ko': '%s · 음가 %s' % (name, sound)},
        {'pos': '', 'ko': '뜻 — %s' % mean},
    ]
    if picto:
        meanings.append({'pos': '', 'ko': '상형 — %s' % picto})
    key, tts_name = AUDIO.get(letter, ('', ''))
    assert key, '음원 키 없음: %r' % letter
    return {
        'en': letter,
        'ipa': '',
        # 음원 파일명 키(앱 _audioKey 가 읽는다) · TTS 가 읽을 글자 이름
        # ttsName 은 생성 스크립트용, heName 은 DB(analysis.he_name)로 넘어간다 —
        # edge function 쪽 생성기는 JSON 파일이 아니라 DB 를 읽기 때문이다.
        'audio': key,
        'ttsName': tts_name,
        'heName': tts_name,
        'level': '',                      # CEFR 배지 없음 (빈 값이면 배지가 렌더되지 않는다)
        'meanings': [
            # seed_official.map_word 가 meanings[0] 에서 base/ctx/sentence 를 뽑는다
            {'pos': '', 'ko': meanings[0]['ko'], 'ex': ex, 'tr': '%s — %s' % (ex_read, ex_ko)},
        ] + meanings[1:],
        'syn': [], 'deriv': [], 'roots': [], 'colloc': [],
        'etymHint': '', 'exam': None,
        'tip': tip_of(gematria, sofit, letter, name),
        '_num': num,
    }

words = [to_word(r) for r in ROWS]
assert len(words) == 22, len(words)
days = {1: words[:11], 2: words[11:]}
for d, ws in days.items():
    for w in ws: w.pop('_num', None)
    p = 'hebrew-alefbet-day%d.json' % d
    io.open(p, 'w', encoding='utf-8').write(
        json.dumps({'words': ws}, ensure_ascii=False, indent=1) + '\n')
    print('%s  %d장' % (p, len(ws)))
